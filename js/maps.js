function commuteRoute(city){
  const iw = 2;                                      // Waitsburg's index on US-12
  if (city === 'waitsburg') return [];
  if (city === 'dayton') return US12.slice(0, iw + 1).reverse();
  const toPasco = US12.slice(iw);
  if (city === 'wallawalla') return US12.slice(iw, 5);
  if (city === 'pasco') return toPasco;
  return toPasco.concat(SPUR[city].slice(1));
}
const pathD = pts => pts.map((p,i) => `${i?'L':'M'}${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join('');

// push overlapping pins apart (the Tri-Cities sit close together), keeping them near their real spots
function spread(pts, min, w, h){
  const ks = Object.keys(pts), home = {}; ks.forEach(k => home[k] = pts[k].slice());
  for (let it = 0; it < 200; it++) {
    for (let i = 0; i < ks.length; i++) for (let j = i+1; j < ks.length; j++) {
      const a = pts[ks[i]], b = pts[ks[j]]; let dx = b[0]-a[0], dy = b[1]-a[1], d = Math.hypot(dx, dy);
      if (d >= min) continue; if (d < 0.01) { dx = 1; dy = 1; d = 1.4; }
      const p = (min - d) / 2, ux = dx/d, uy = dy/d; a[0] -= ux*p; a[1] -= uy*p; b[0] += ux*p; b[1] += uy*p;
    }
    ks.forEach(k => { const p = pts[k]; p[0] += (home[k][0]-p[0])*0.02; p[1] += (home[k][1]-p[1])*0.02;
      p[0] = Math.max(18, Math.min(w-18, p[0])); p[1] = Math.max(18, Math.min(h-18, p[1])); });
  }
  return pts;
}

