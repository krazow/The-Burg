#!/usr/bin/env python3
"""Bake real river shapes into index.html for the region map.

Source: Natural Earth 1:10m rivers (public domain), from github.com/nvkelso/natural-earth-vector:
  geojson/ne_10m_rivers_lake_centerlines.geojson  (Columbia; the Snake is stored under the name "Columbia" there)
  geojson/ne_10m_rivers_north_america.geojson     (Yakima)
The Walla Walla and Touchet rivers are too small for Natural Earth, so the map keeps hand-traced lines for them.

Usage: python3 tools/make-geo.py <folder with the two geojson files>
Rewrites the block between the GEO:RIVERS markers in index.html.
"""
import json, sys, os, re

BOX = (-119.42, -117.80, 45.95, 46.47)      # west, east, south, north: the region map (same as RBB in index.html)
PAD = 0.12                                   # keep a little past the edge so lines run off the map cleanly
TOL = 0.0025                                 # simplification tolerance in degrees (~200 m)

def lines_of(g):
    return g['coordinates'] if g['type'] == 'MultiLineString' else [g['coordinates']]

def inside(p):
    w, e, s, n = BOX
    return w - PAD <= p[0] <= e + PAD and s - PAD <= p[1] <= n + PAD

def clip(line):
    """Pieces of a line inside the padded box, each with one point beyond the edge on either end."""
    out, cur = [], []
    for i, p in enumerate(line):
        if inside(p):
            if not cur and i > 0: cur.append(line[i - 1])
            cur.append(p)
        elif cur:
            cur.append(p); out.append(cur); cur = []
    if cur: out.append(cur)
    return out

def simplify(pts, tol):
    """Douglas-Peucker."""
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    L = (dx * dx + dy * dy) ** 0.5 or 1e-12
    dmax, idx = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / L
        if d > dmax: dmax, idx = d, i
    if dmax <= tol: return [pts[0], pts[-1]]
    return simplify(pts[:idx + 1], tol)[:-1] + simplify(pts[idx:], tol)

def pick(path, test):
    d = json.load(open(path))
    got = []
    for f in d['features']:
        if f['geometry'] and test(f):
            for ln in lines_of(f['geometry']):
                got += clip(ln)
    return got

def main(src):
    lake = os.path.join(src, 'ne_10m_rivers_lake_centerlines.geojson')
    na = os.path.join(src, 'ne_10m_rivers_north_america.geojson')
    def ext(f):
        xs = [p[0] for ln in lines_of(f['geometry']) for p in ln]
        return min(xs), max(xs)
    rivers = {
        # the main stem reaches the Pacific (west of -122); the Snake's feature runs east into Idaho/Wyoming
        'Columbia': pick(lake, lambda f: f['properties'].get('name') == 'Columbia' and ext(f)[0] < -122),
        'Snake':    pick(lake, lambda f: f['properties'].get('name') == 'Columbia' and ext(f)[0] > -119.2 and ext(f)[1] > -112),
        'Yakima':   pick(na,   lambda f: f['properties'].get('name') == 'Yakima'),
    }
    geo = {}
    for name, parts in rivers.items():
        if not parts: sys.exit(f'{name}: nothing found inside the map')
        geo[name] = [[[round(y, 4), round(x, 4)] for x, y in simplify(p, TOL)] for p in parts]   # [lat, lon]
        print(f'{name}: {len(parts)} piece(s), {sum(len(p) for p in geo[name])} points')
    html_path = os.path.join(os.path.dirname(__file__), '..', 'index.html')
    html = open(html_path, encoding='utf-8').read()
    block = ('/* GEO:RIVERS (generated by tools/make-geo.py from Natural Earth 1:10m rivers, public domain) */\n'
             'const GEO_RIVERS = ' + json.dumps(geo, separators=(',', ':')) + ';\n/* /GEO:RIVERS */')
    if '/* GEO:RIVERS' in html:
        html = re.sub(r'/\* GEO:RIVERS.*?/\* /GEO:RIVERS \*/', lambda m: block, html, flags=re.S)
    else:
        html = html.replace('/* ---- region map: a lon/lat box', block + '\n/* ---- region map: a lon/lat box', 1)
    open(html_path, 'w', encoding='utf-8').write(html)
    print('index.html updated')

if __name__ == '__main__':
    if len(sys.argv) != 2: sys.exit(__doc__)
    main(sys.argv[1])
